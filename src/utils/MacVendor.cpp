std::string MacVendorLookup::Lookup(const std::string& macAddress) const {
    if (macAddress.empty() || macAddress == "00:00:00:00:00:00") return "(Unknown vendor)";

    // Extract first 3 octets
    std::string mac;
    int octets = 0;
    for (char c : macAddress) {
        if (c == ':' || c == '-') {
            octets++;
            if (octets >= 3) break;
        } else if (std::isxdigit(static_cast<unsigned char>(c))) {
            mac += static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
        }
    }

    auto it = vendors_.find(mac);
    if (it != vendors_.end()) return it->second;
    return "(Unknown vendor)";
}

